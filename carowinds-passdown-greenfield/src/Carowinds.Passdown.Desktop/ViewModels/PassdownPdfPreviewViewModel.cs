        IsSaving = true;
        ActionMessage = null;
        ActionMessageIsError = false;
        try
        {
            var document = await EnsureLatestDocumentAsync().ConfigureAwait(true);
            if (document is null)
            {
                SetActionMessage(_lastFailureMessage ?? "The PDF could not be created for this date yet.", isError: true);
                return;
            }

            var result = await _savePicker.SaveAsync(document.Bytes, SuggestedFileName(document.Date)).ConfigureAwait(true);
            switch (result.Outcome)
            {
                case PdfSaveOutcome.Saved:
                    SetActionMessage("PDF saved.", isError: false);
                    break;
                case PdfSaveOutcome.Cancelled:
                    break;
                default:
                    SetActionMessage(result.ErrorMessage ?? "The PDF could not be saved. Try again.", isError: true);
                    break;
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogError(ex, "Save PDF from the preview failed unexpectedly.");
            SetActionMessage("The PDF could not be saved. Try again.", isError: true);
        }
        finally
        {
            IsSaving = false;
        }
    }

