    [RelayCommand(CanExecute = nameof(CanExport))]
    private async Task PrintAsync()
    {
        IsPrinting = true;
        ActionMessage = null;
        ActionMessageIsError = false;
        try
        {
            var document = await EnsureLatestDocumentAsync().ConfigureAwait(true);
            if (document is null)
            {
                SetActionMessage(_lastFailureMessage ?? "The Passdown could not be created for printing. Try again.", isError: true);
                return;
            }

            var result = await _printService.PrintAsync(new PdfPrintRequest(document.Bytes, DocumentTitle(document), document.PageCount)).ConfigureAwait(true);
            switch (result.Outcome)
            {
                case PdfPrintOutcome.Printed:
                    SetActionMessage(result.PrinterName is { Length: > 0 } printer ? $"Sent to {printer}." : "Sent to the printer.", isError: false);
                    break;
                case PdfPrintOutcome.Cancelled:
                    break;
                default:
                    SetActionMessage(result.Message ?? "Printing failed. Try again.", isError: true);
                    break;
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogError(ex, "Printing the Associate Passdown failed unexpectedly.");
            SetActionMessage("Printing failed. Try again.", isError: true);
        }
        finally
        {
            IsPrinting = false;
        }
    }

