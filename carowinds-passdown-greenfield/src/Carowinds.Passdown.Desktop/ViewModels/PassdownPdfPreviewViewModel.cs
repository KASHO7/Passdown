    private async Task LoadPreferencesAsync()
    {
        PdfPreviewLayoutPreferences preferences;
        try
        {
            preferences = await _layoutStore.LoadAsync().ConfigureAwait(true);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogWarning(ex, "PDF preview layout preferences could not be loaded; using defaults.");
            preferences = PdfPreviewLayoutPreferences.BuiltIn;
        }

        _isLoadingPreferences = true;
        try
        {
            var wasShown = IsPreviewPaneShown;
            IsPreviewRequested = preferences.IsPreviewVisible;
            PreviewPaneWidth = preferences.PreviewPaneWidth > 0 ? preferences.PreviewPaneWidth : PdfPreviewLayoutPreferences.DefaultPreviewPaneWidth;
            FitMode = preferences.FitMode;
            Zoom = PdfPreviewZoom.Clamp(preferences.Zoom);
            UpdatePageDisplaySize();
            if (wasShown && !IsPreviewPaneShown)
            {
                OnPaneVisibilityChanged(wasShown);
            }
        }
        finally
        {
            _isLoadingPreferences = false;
        }
    }

    private void SavePreferences()
    {
        if (_isLoadingPreferences)
        {
            return;
        }

        var preferences = new PdfPreviewLayoutPreferences(IsPreviewRequested, PreviewPaneWidth, FitMode, Zoom);
        PendingPreferenceSave = SavePreferencesAsync(preferences);
    }

    private async Task SavePreferencesAsync(PdfPreviewLayoutPreferences preferences)
    {
        try
        {
            await _layoutStore.SaveAsync(preferences).ConfigureAwait(true);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            // A layout preference is never worth an error message; the layout still works this session.
            _logger?.LogWarning(ex, "PDF preview layout preferences could not be saved.");
        }
    }
