    [RelayCommand]
    private void FitWidth() => ApplyZoom(ComputeFitZoom(PdfPreviewFitMode.FitWidth, _pageSize), PdfPreviewFitMode.FitWidth, persist: true);

    [RelayCommand]
    private void FitPage() => ApplyZoom(ComputeFitZoom(PdfPreviewFitMode.FitPage, _pageSize), PdfPreviewFitMode.FitPage, persist: true);

    /// <summary>Regenerates the preview now, even when nothing appears to have changed.</summary>
    [RelayCommand]
    private Task Refresh()
    {
        _contentVersion++;
        PendingRefresh = RefreshNowAsync();
        return PendingRefresh;
    }

    private void ApplyZoom(double zoom, PdfPreviewFitMode mode, bool persist)
    {
        var clamped = PdfPreviewZoom.Clamp(zoom);
        var changed = Math.Abs(clamped - Zoom) > 0.0001 || mode != FitMode;
        Zoom = clamped;
        FitMode = mode;
        UpdatePageDisplaySize();
        SchedulePageRenderIfNeeded();
        if (persist && changed)
        {
            SavePreferences();
        }
    }

    private double ComputeFitZoom(PdfPreviewFitMode mode, PdfPageSize page) => mode switch
    {
        PdfPreviewFitMode.FitWidth => _viewportWidth > 0 ? PdfPreviewZoom.FitWidth(page, _viewportWidth) : Zoom,
        PdfPreviewFitMode.FitPage => _viewportWidth > 0 ? PdfPreviewZoom.FitPage(page, _viewportWidth, _viewportHeight) : Zoom,
        _ => Zoom,
    };

    private void UpdatePageDisplaySize()
    {
        PageDisplayWidth = Math.Round(_pageSize.WidthPoints * PdfPreviewZoom.DipsPerPoint * Zoom, 1);
        PageDisplayHeight = Math.Round(_pageSize.HeightPoints * PdfPreviewZoom.DipsPerPoint * Zoom, 1);
    }

    private double TargetPixelsPerPoint(PdfPageSize page, double zoom)
    {
        var pixelsPerPoint = zoom * PdfPreviewZoom.DipsPerPoint * _renderScaling;
        return Math.Min(pixelsPerPoint, MaxRenderedPixelWidth / Math.Max(1, page.WidthPoints));
    }

    private void SchedulePageRenderIfNeeded()
    {
        if (_raster is null || !HasPage)
        {
            return;
        }

        var needed = TargetPixelsPerPoint(_pageSize, Zoom);
        if (needed <= _renderedPixelsPerPoint * 1.05 && needed >= _renderedPixelsPerPoint * 0.6)
        {
            return; // the current bitmap scales cleanly; no re-render
        }

        _pageRenderCts?.Cancel();
        var cts = new CancellationTokenSource();
        _pageRenderCts = cts;
        PendingPageRender = DebouncedPageRenderAsync(cts.Token);
    }

    private async Task DebouncedPageRenderAsync(CancellationToken token)
    {
        try
        {
            await _delay(PageRenderDebounce, token).ConfigureAwait(true);
        }
        catch (OperationCanceledException)
        {
            return;
        }

        if (!token.IsCancellationRequested)
        {
            await RenderCurrentPageAsync(resetFit: false).ConfigureAwait(true);
        }
    }

