    /// <summary>The width available to editor + preview together (DIPs).</summary>
    public void UpdateAvailableWidth(double availableWidth)
    {
        if (!double.IsFinite(availableWidth) || availableWidth <= 0 || Math.Abs(availableWidth - _availableWidth) < 0.5)
        {
            return;
        }

        var wasShown = IsPreviewPaneShown;
        _availableWidth = availableWidth;
        IsNarrowLayout = PdfPreviewLayout.IsNarrow(availableWidth);
        if (!IsNarrowLayout)
        {
            IsPreviewInFrontWhenNarrow = false;
        }

        OnPropertyChanged(nameof(Layout));
        OnPropertyChanged(nameof(PaneMode));
        OnPropertyChanged(nameof(IsPreviewPaneShown));
        OnPropertyChanged(nameof(IsEditorShown));
        OnPropertyChanged(nameof(IsSplitLayout));
        OnPropertyChanged(nameof(TogglePreviewLabel));
        OnPropertyChanged(nameof(TogglePreviewHelpText));
        OnPropertyChanged(nameof(EffectivePreviewPaneWidth));
        OnPaneVisibilityChanged(wasShown);
    }

    /// <summary>The divider was released at <paramref name="previewWidth"/>: remember it (clamped) locally.</summary>
    public void CommitPreviewPaneWidth(double previewWidth)
    {
        if (!double.IsFinite(previewWidth) || previewWidth <= 0)
        {
            return;
        }

        var clamped = double.IsFinite(_availableWidth) ? PdfPreviewLayout.ClampPreviewWidth(previewWidth, _availableWidth) : Math.Max(PdfPreviewLayout.MinPreviewWidth, previewWidth);
        if (Math.Abs(clamped - PreviewPaneWidth) < 0.5)
        {
            return;
        }

        PreviewPaneWidth = clamped;
        SavePreferences();
    }

    /// <summary>The page viewport size and the window's render scaling (DPI) — drives fit zoom and render resolution.</summary>
    public void UpdateViewport(double width, double height, double renderScaling)
    {
        if (!double.IsFinite(width) || !double.IsFinite(height) || width <= 0 || height <= 0)
        {
            return;
        }

        var scaling = double.IsFinite(renderScaling) && renderScaling > 0 ? renderScaling : 1.0;
        if (Math.Abs(width - _viewportWidth) < 0.5 && Math.Abs(height - _viewportHeight) < 0.5 && Math.Abs(scaling - _renderScaling) < 0.001)
        {
            return;
        }

        _viewportWidth = width;
        _viewportHeight = height;
        _renderScaling = scaling;
        if (FitMode != PdfPreviewFitMode.Custom)
        {
            ApplyZoom(ComputeFitZoom(FitMode, _pageSize), FitMode, persist: false);
        }
        else
        {
            UpdatePageDisplaySize();
            SchedulePageRenderIfNeeded();
        }
    }

