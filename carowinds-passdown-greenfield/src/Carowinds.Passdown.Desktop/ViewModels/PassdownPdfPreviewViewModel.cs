    private void StartUpdatingIndicatorDelay()
    {
        if (_indicatorCts is not null || IsUpdatingIndicatorVisible)
        {
            return; // already counting down (or shown) for this stretch of Updating
        }

        var cts = new CancellationTokenSource();
        _indicatorCts = cts;
        _ = ShowUpdatingIndicatorAfterDelayAsync(cts);
    }

    private async Task ShowUpdatingIndicatorAfterDelayAsync(CancellationTokenSource cts)
    {
        try
        {
            await _indicatorDelay(UpdatingIndicatorDelay, cts.Token).ConfigureAwait(true);
        }
        catch (OperationCanceledException)
        {
            return;
        }

        if (cts.IsCancellationRequested || !ReferenceEquals(cts, _indicatorCts))
        {
            return;
        }

        _indicatorCts = null;
        cts.Dispose();
        if (Status == PdfPreviewStatus.Updating && ShouldAutoRender && HasPage)
        {
            // Without a page the centered status message already says what is happening.
            IsUpdatingIndicatorVisible = true;
        }
    }

    private void StopUpdatingIndicator()
    {
        if (_indicatorCts is { } cts)
        {
            _indicatorCts = null;
            cts.Cancel();
        }

        IsUpdatingIndicatorVisible = false;
    }

    private static Task NeverElapses(TimeSpan delay, CancellationToken cancellationToken) =>
        Task.Delay(Timeout.InfiniteTimeSpan, cancellationToken);

    private async Task<PassdownPdfDocument?> GenerateLatestAsync(bool display)
    {
        _lastFailureMessage = null;
        var capture = _capture();
        var version = _contentVersion;
        if (capture.Request is not { } request)
        {
            _lastFailureMessage = capture.WaitingText is { Length: > 0 } waiting ? $"{waiting} Try again in a moment." : "This date is still loading. Try again in a moment.";
            if (display)
            {
                ReleaseDisplay();
                Status = PdfPreviewStatus.Waiting;
                StatusText = capture.WaitingText ?? "Loading this date's preview…";
            }

            return null;
        }

        if (_document is { } existing && existing.ContentVersion == version && existing.Date == request.Date && existing.Template == request.Template)
        {
            if (display && !_documentDisplayed)
            {
                await DisplayAsync(existing, ++_generation).ConfigureAwait(true);
            }

            return existing;
        }

        var generation = ++_generation;
        if (display)
        {
            Status = PdfPreviewStatus.Updating;
            StatusText = HasPage ? "Updating preview…" : "Creating preview…";
        }

        AssociatePassdownPdfResult result;
        DateTimeOffset generatedAt = _now();
        try
        {
            GenerationCount++;
            result = await _scheduler.Run(() => _exportService.GeneratePdf(request.Workspace, generatedAt, request.Template)).ConfigureAwait(true);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogError(ex, "Generating the Associate Passdown preview PDF failed for {OperatingDate}.", request.Date);
            _lastFailureMessage = "The Passdown PDF could not be created. Your draft is unchanged. Try again.";
            if (display && generation == _generation)
            {
                ShowError(_lastFailureMessage);
            }

            return null;
        }

        if (result.PdfBytes is not { } bytes)
        {
            _lastFailureMessage = result.Preflight.Reasons.Count > 0 ? string.Join(" ", result.Preflight.Reasons) : "The PDF could not be created for this date yet.";
            if (display && generation == _generation)
            {
                ReleaseDisplay();
                Status = PdfPreviewStatus.NoDocument;
                StatusText = _lastFailureMessage;
            }

            return null;
        }

        var document = new PassdownPdfDocument(bytes, request.Date, request.Template, Math.Max(1, result.PageCount), version, generatedAt, PdfContentFingerprint.Compute(bytes));

        // Install as the current document unless a newer state's document is already installed, or it was
        // built before the last date change (Phase 34B-1: a late previous-date result is never installed).
        if (document.ContentVersion < _minimumInstallVersion)
        {
            // Print / Save PDF clicked just before the date changed: refuse rather than hand on the previous
            // date's PDF after the editor has moved on. Never installed or displayed.
            _lastFailureMessage = "The selected date changed while the Passdown was being prepared. Nothing was printed or saved — try again.";
            return null;
        }

        if (_document is null || document.ContentVersion >= _document.ContentVersion)
        {
            var sameAsShown = _documentDisplayed && HasPage && _document is { } shown
                && shown.Fingerprint == document.Fingerprint && shown.Date == document.Date && shown.Template == document.Template;
            _document = document;
            if (sameAsShown)
            {
                // Identical content: keep the page, page number and zoom exactly as they are.
                if (display && generation == _generation)
                {
                    Status = PdfPreviewStatus.Ready;
                    StatusText = null;
                    DocumentCaption = Caption(document);
                }

                return document;
            }

            _documentDisplayed = false;
        }

        if (display && generation == _generation)
        {
            await DisplayAsync(document, generation).ConfigureAwait(true);
        }

        return document;
    }

    private async Task DisplayAsync(PassdownPdfDocument document, int generation)
    {
        if (_rasterizer is not { } rasterizer)
        {
            return;
        }

        var requestedPage = PageIndex;
        var fitMode = FitMode;
        var zoom = Zoom;
        var viewportWidth = _viewportWidth;
        var viewportHeight = _viewportHeight;
        var renderScaling = _renderScaling;
        _pageRenderToken++;

        DisplayResult rendered;
        try
        {
            rendered = await _scheduler.Run(() =>
            {
                var raster = rasterizer.Open(document.Bytes);
                IImage? image = null;
                try
                {
                    var pageIndex = Math.Clamp(requestedPage, 0, Math.Max(0, raster.PageCount - 1));
                    var size = raster.GetPageSize(pageIndex);
                    var effectiveZoom = fitMode switch
                    {
                        PdfPreviewFitMode.FitWidth when viewportWidth > 0 => PdfPreviewZoom.FitWidth(size, viewportWidth),
                        PdfPreviewFitMode.FitPage when viewportWidth > 0 => PdfPreviewZoom.FitPage(size, viewportWidth, viewportHeight),
                        _ => zoom,
                    };
                    var pixelsPerPoint = Math.Min(effectiveZoom * PdfPreviewZoom.DipsPerPoint * renderScaling, MaxRenderedPixelWidth / Math.Max(1, size.WidthPoints));
                    image = _imageFactory.Create(raster.RenderPage(pageIndex, pixelsPerPoint));
                    return new DisplayResult(raster, image, pageIndex, size, effectiveZoom, pixelsPerPoint);
                }
                catch
                {
                    (image as IDisposable)?.Dispose();
                    raster.Dispose();
                    throw;
                }
            }).ConfigureAwait(true);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogError(ex, "Rendering the Associate Passdown preview failed.");
            if (generation == _generation)
            {
                ShowError("The preview could not be displayed. Your draft is unchanged — Print and Save PDF still use the generated Passdown.");
            }

            return;
        }

        if (generation != _generation || !ShouldAutoRender)
        {
            // Superseded (a newer edit, a date change, or the preview was hidden) — never shown.
            (rendered.Image as IDisposable)?.Dispose();
            rendered.Raster.Dispose();
            return;
        }

        var oldRaster = _raster;
        _raster = rendered.Raster;
        oldRaster?.Dispose();
        _pageSize = rendered.PageSize;
        _renderedPixelsPerPoint = rendered.PixelsPerPoint;
        PageCount = rendered.Raster.PageCount;
        PageIndex = rendered.PageIndex; // clamped: a shorter PDF lands on its last page
        Zoom = PdfPreviewZoom.Clamp(rendered.Zoom);
        UpdatePageDisplaySize();
        SwapPageImage(rendered.Image);
        _documentDisplayed = true;
        DocumentCaption = Caption(document);
        Status = PdfPreviewStatus.Ready;
        StatusText = null;
    }

    private sealed record DisplayResult(IPdfRasterDocument Raster, IImage Image, int PageIndex, PdfPageSize PageSize, double Zoom, double PixelsPerPoint);

    private async Task RenderCurrentPageAsync(bool resetFit)
    {
        if (_raster is not { } raster)
        {
            return;
        }

        var token = ++_pageRenderToken;
        var pageIndex = Math.Clamp(PageIndex, 0, Math.Max(0, raster.PageCount - 1));
        PdfPageSize size;
        try
        {
            size = raster.GetPageSize(pageIndex);
        }
        catch (ObjectDisposedException)
        {
            return;
        }

        if (resetFit && FitMode != PdfPreviewFitMode.Custom)
        {
            Zoom = ComputeFitZoom(FitMode, size);
        }

        _pageSize = size;
        UpdatePageDisplaySize();
        var pixelsPerPoint = TargetPixelsPerPoint(size, Zoom);

        IImage image;
        try
        {
            image = await _scheduler.Run(() => _imageFactory.Create(raster.RenderPage(pageIndex, pixelsPerPoint))).ConfigureAwait(true);
        }
        catch (ObjectDisposedException)
        {
            return; // the document was replaced meanwhile
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger?.LogError(ex, "Rendering preview page {Page} failed.", pageIndex + 1);
            if (token == _pageRenderToken)
            {
                ShowError("This page of the preview could not be displayed.");
            }

            return;
        }

        if (token != _pageRenderToken || !ReferenceEquals(raster, _raster))
        {
            (image as IDisposable)?.Dispose();
            return;
        }

        _renderedPixelsPerPoint = pixelsPerPoint;
        SwapPageImage(image);
    }

    private void SwapPageImage(IImage? image)
    {
        var old = PageImage;
        PageImage = image;
        if (old is IDisposable disposable && !ReferenceEquals(old, image))
        {
            disposable.Dispose();
        }
    }

    private void ReleaseDisplay()
    {
        _pageRenderToken++;
        _pageRenderCts?.Cancel();
        SwapPageImage(null);
        _raster?.Dispose();
        _raster = null;
        _documentDisplayed = false;
        _renderedPixelsPerPoint = 0;
    }

    private void ShowError(string message)
    {
        ReleaseDisplay();
        Status = PdfPreviewStatus.Error;
        StatusText = message;
    }

    private static string Caption(PassdownPdfDocument document) =>
        $"{document.Date.ToString("ddd, MMM d, yyyy", CultureInfo.GetCultureInfo("en-US"))} · {AssociatePassdownTemplateOption.For(document.Template).Label}";

