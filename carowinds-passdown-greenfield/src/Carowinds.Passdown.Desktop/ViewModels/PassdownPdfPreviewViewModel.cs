    [RelayCommand]
    private void TogglePreview()
    {
        if (IsPreviewPaneShown)
        {
            HidePreview();
        }
        else
        {
            ShowPreview();
        }
    }

    [RelayCommand]
    private void ShowPreview()
    {
        var wasShown = IsPreviewPaneShown;
        if (IsNarrowLayout)
        {
            IsPreviewInFrontWhenNarrow = true; // transient: the saved Show/Hide choice is about the side-by-side layout
        }
        else if (!IsPreviewRequested)
        {
            IsPreviewRequested = true;
            SavePreferences();
        }

        OnPaneVisibilityChanged(wasShown);
    }

    [RelayCommand]
    private void HidePreview()
    {
        var wasShown = IsPreviewPaneShown;
        if (IsNarrowLayout)
        {
            IsPreviewInFrontWhenNarrow = false;
        }
        else if (IsPreviewRequested)
        {
            IsPreviewRequested = false;
            SavePreferences();
        }

        OnPaneVisibilityChanged(wasShown);
    }

    private void OnPaneVisibilityChanged(bool wasShown)
    {
        OnPropertyChanged(nameof(Layout));
        var shown = IsPreviewPaneShown;
        if (shown == wasShown)
        {
            return;
        }

        if (!shown)
        {
            // Hidden: stop pending work and free the rasterized page; the generated document is kept so a
            // later Print/Save of an unchanged Passdown reuses it.
            CancelQuietWindow();
            _refreshAgain = false;
            _generation++;
            ReleaseDisplay();
            Status = PdfPreviewStatus.Idle;
            StatusText = null;
            return;
        }

        if (IsAvailable)
        {
            Status = PdfPreviewStatus.Updating;
            StatusText = "Updating preview…";
            PendingRefresh = RefreshNowAsync();
        }
    }

